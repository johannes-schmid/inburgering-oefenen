-- ONA: het portfolio van de kandidaat, en het oefenen van het eindgesprek.
--
-- ONA is géén examen in de zin van deze database: er zijn geen vragen, geen opties en geen score.
-- Het zijn acht resultaatkaarten die de kandidaat zelf invult voor één gewenst beroep, en die hij
-- daarna zelf bij DUO inlevert. Daarom staat ONA níet in `skills` (de `scoring`-check kent alleen
-- `mcq` en `open`) en niet in `exams`. ONA leeft alleen op de module-as (`user_metadata.modules`
-- bevat `'ona'`) en in de drie tabellen hieronder.
--
-- 1. `ona_portfolios` — één per kandidaat: het gewenste beroep. Eén beroep voor alle acht kaarten
--    is precies wat DUO controleert ("alle kaarten over hetzelfde beroep").
-- 2. `ona_card_entries` — de antwoorden per kaart, als jsonb op prompt-id. De prompts zelf staan in
--    `data/ona/cards.ts` (inhoud van de docent, in de repo), dus hier staat alleen wat de
--    kandidaat schreef. `ai_flags` is de laatste uitkomst van de check: alleen vragen, nooit tekst.
-- 3. `ona_practice_sessions` — één oefengesprek: het transcript en de terugblik.
--
-- Bewijzen (diploma's, vacatures, cv) worden hier NIET opgeslagen. Ze gaan rechtstreeks naar DUO;
-- hier staat alleen een vinkje per bewijs. Geen documenten met persoonsgegevens, geen bucket.
--
-- Daarnaast twee bestaande checks verbreed, zodat de check en het oefengesprek door dezelfde
-- rem en hetzelfde kostenregister gaan als het nakijken:
--   - `grade_rate_log.skill` kent nu ook `'ona'`;
--   - `ai_usage.kind` kent nu ook `'ona_check'` en `'ona_gesprek'`.

CREATE TABLE IF NOT EXISTS public.ona_portfolios (
  id          bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     uuid        NOT NULL UNIQUE REFERENCES auth.users(id) ON DELETE CASCADE,
  beroep      text        NOT NULL CHECK (length(btrim(beroep)) BETWEEN 2 AND 120),
  -- Welke wet: ONA (Wet inburgering 2013) of de MAP van de gemeente (Wet 2021). Alleen voor de
  -- tekst op het scherm; de kaarten zijn dezelfde acht thema's.
  route       text        NOT NULL DEFAULT 'onbekend' CHECK (route IN ('wi2013', 'map', 'onbekend')),
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE public.ona_portfolios IS
  'ONA: het gewenste beroep van de kandidaat. Eén rij per gebruiker; alle acht kaarten gaan over dit beroep.';

DROP TRIGGER IF EXISTS ona_portfolios_touch ON public.ona_portfolios;
CREATE TRIGGER ona_portfolios_touch BEFORE UPDATE ON public.ona_portfolios
  FOR EACH ROW EXECUTE FUNCTION public.touch_updated_at();

CREATE TABLE IF NOT EXISTS public.ona_card_entries (
  portfolio_id  bigint      NOT NULL REFERENCES public.ona_portfolios(id) ON DELETE CASCADE,
  card_no       smallint    NOT NULL CHECK (card_no BETWEEN 1 AND 8),
  answers       jsonb       NOT NULL DEFAULT '{}'::jsonb,
  evidence      jsonb       NOT NULL DEFAULT '{}'::jsonb,
  status        text        NOT NULL DEFAULT 'concept' CHECK (status IN ('concept', 'klaar')),
  ai_flags      jsonb,
  ai_checked_at timestamptz,
  updated_at    timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (portfolio_id, card_no)
);

COMMENT ON TABLE public.ona_card_entries IS
  'ONA: de antwoorden van de kandidaat per resultaatkaart (prompt-id → tekst). De prompts staan in data/ona/cards.ts.';

DROP TRIGGER IF EXISTS ona_card_entries_touch ON public.ona_card_entries;
CREATE TRIGGER ona_card_entries_touch BEFORE UPDATE ON public.ona_card_entries
  FOR EACH ROW EXECUTE FUNCTION public.touch_updated_at();

CREATE TABLE IF NOT EXISTS public.ona_practice_sessions (
  id          bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     uuid        NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  card_nos    smallint[]  NOT NULL DEFAULT '{}',
  transcript  jsonb       NOT NULL DEFAULT '[]'::jsonb,
  feedback    jsonb,
  finished_at timestamptz,
  created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS ona_practice_sessions_user_idx
  ON public.ona_practice_sessions (user_id, created_at DESC);

COMMENT ON TABLE public.ona_practice_sessions IS
  'ONA: één oefengesprek. Transcript en terugblik; geen cijfer, geen geslaagd.';

-- ── RLS: de kandidaat ziet en schrijft alleen zijn eigen rijen; de admin leest mee. ──────────

ALTER TABLE public.ona_portfolios        ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ona_card_entries      ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ona_practice_sessions ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Own ona portfolio" ON public.ona_portfolios;
CREATE POLICY "Own ona portfolio" ON public.ona_portfolios
  FOR ALL USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "Admins read ona portfolios" ON public.ona_portfolios;
CREATE POLICY "Admins read ona portfolios" ON public.ona_portfolios
  FOR SELECT USING (public.is_admin());

DROP POLICY IF EXISTS "Own ona card entries" ON public.ona_card_entries;
CREATE POLICY "Own ona card entries" ON public.ona_card_entries
  FOR ALL
  USING (EXISTS (SELECT 1 FROM public.ona_portfolios p WHERE p.id = portfolio_id AND p.user_id = auth.uid()))
  WITH CHECK (EXISTS (SELECT 1 FROM public.ona_portfolios p WHERE p.id = portfolio_id AND p.user_id = auth.uid()));

DROP POLICY IF EXISTS "Admins read ona card entries" ON public.ona_card_entries;
CREATE POLICY "Admins read ona card entries" ON public.ona_card_entries
  FOR SELECT USING (public.is_admin());

DROP POLICY IF EXISTS "Own ona practice sessions" ON public.ona_practice_sessions;
CREATE POLICY "Own ona practice sessions" ON public.ona_practice_sessions
  FOR ALL USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "Admins read ona practice sessions" ON public.ona_practice_sessions;
CREATE POLICY "Admins read ona practice sessions" ON public.ona_practice_sessions
  FOR SELECT USING (public.is_admin());

GRANT SELECT, INSERT, UPDATE, DELETE ON public.ona_portfolios, public.ona_card_entries, public.ona_practice_sessions TO authenticated;

