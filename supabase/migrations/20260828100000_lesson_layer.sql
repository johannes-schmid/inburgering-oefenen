-- Beheersing telt op HET CONCEPT, over de onderdelen heen: een goed antwoord in de
-- Luisteren-les en een goed antwoord in de Schrijven-les verhogen dezelfde rij. Dat is de
-- juiste keuze en niet de gemakkelijke — "herkent `omdat` op het gehoor" en "produceert
-- `omdat` schriftelijk" zijn de tier 0 versus tier 2 op `lesson_items`, niet twee concepten.
--
-- `mastery_pct` is ONS getal en heet dat ook. Het is geen voorspelling van een DUO-uitslag:
-- SEO/facts.md §9 verbiedt een onnavolgbare slaagnorm, en een percentage dat als slaagkans
-- leest zou datzelfde doen.
CREATE TABLE IF NOT EXISTS public.user_concept_mastery (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id        uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  concept_id     integer NOT NULL REFERENCES public.concepts(id) ON DELETE CASCADE,
  seen           integer NOT NULL DEFAULT 0,
  correct        integer NOT NULL DEFAULT 0,
  -- Goede antwoorden op rij; de "nog N goede antwoorden en dit concept staat op beheerst"-regel.
  streak         integer NOT NULL DEFAULT 0,
  -- Apart geteld per trap, want receptief kunnen en productief kunnen zijn niet hetzelfde.
  correct_receptief  integer NOT NULL DEFAULT 0,
  seen_receptief     integer NOT NULL DEFAULT 0,
  correct_productief integer NOT NULL DEFAULT 0,
  seen_productief    integer NOT NULL DEFAULT 0,
  mastery_pct    smallint NOT NULL DEFAULT 0 CHECK (mastery_pct BETWEEN 0 AND 100),
  updated_at     timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT user_concept_mastery_key UNIQUE (user_id, concept_id)
);

CREATE INDEX IF NOT EXISTS user_concept_mastery_user_idx
  ON public.user_concept_mastery (user_id);

