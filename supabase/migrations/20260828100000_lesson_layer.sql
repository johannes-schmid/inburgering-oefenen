-- ---------------------------------------------------------------------------
-- 8. RLS
-- ---------------------------------------------------------------------------
--
-- Contenttabellen: publiek lezen, admin schrijven — exact zoals `questions`,
-- `question_options`, `stimuli` en `sections` het al doen. Het gevolg is dat een nog niet
-- nagekeken les langs zijn URL leesbaar is, en dat is bedoeld: precies dát maakt reviewen
-- mogelijk. De publicatiegate zit in de applicatielaag (`review_status = 'validated'`), net
-- zoals `exams.published` daar zit en niet in een policy.
--
-- Let op wat hier NIET verandert: `lesson_item_options.is_correct` is publiek leesbaar, net
-- als `question_options.is_correct`. Dat is de bestaande conventie waar de examenspeler op
-- leunt. Wat nooit publiek mag zijn, is een rubriek of een `model_answer`; daar komt in deze
-- laag niets van voor, en `open_zin` draagt zijn voorbeeldantwoord bewust wél in de payload
-- omdat de kandidaat het zelf moet kunnen vergelijken.

