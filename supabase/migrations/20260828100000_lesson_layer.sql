DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY[
    'concept_groups', 'concepts', 'concept_onderdelen', 'lesson_blocks', 'lessons',
    'lesson_concepts', 'lesson_items', 'lesson_item_options', 'lesson_words',
    'block_outcomes', 'question_concepts', 'open_task_concepts'
  ] LOOP
    EXECUTE format(
      'DROP POLICY IF EXISTS "Public read %1$s" ON public.%1$I', t);
    EXECUTE format(
      'CREATE POLICY "Public read %1$s" ON public.%1$I FOR SELECT USING (true)', t);
    EXECUTE format(
      'DROP POLICY IF EXISTS "Admins write %1$s" ON public.%1$I', t);
    EXECUTE format(
      'CREATE POLICY "Admins write %1$s" ON public.%1$I FOR ALL USING (is_admin()) WITH CHECK (is_admin())', t);
  END LOOP;
END $$;

